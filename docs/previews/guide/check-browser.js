async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const base = "http://127.0.0.1:4178/";
  const sample = "/Users/jsonse/.codex/worktrees/org-guide-prototypes/race-pace/docs/previews/guide/public/fieldnotes/guide-assets/event-to-ticket.mp4";
  const results = [];
  for (let choice = 1; choice <= 5; choice++) {
    await page.goto(`${base}?choice=${choice}`);
    await page.getByRole("searchbox", { name: "Search guides" }).fill("allocate");
    assert((await page.locator("main").innerText()).includes("Set categories and available slots"), `Description search failed for choice ${choice}`);
    await page.getByRole("button", { name: "Clear search" }).click();
    await page.getByRole("searchbox", { name: "Search guides" }).fill("unfindable-xyz");
    await page.getByRole("heading", { name: "No matching guides" }).waitFor();
    await page.getByRole("button", { name: "Clear filters" }).click();
    assert(await page.getByRole("button", { name: "Upload video", exact: true }).count() === 0, "Org admin received an upload control");
    results.push({ choice, search: "pass", empty: "pass", role: "pass" });
  }
  await page.goto(base);
  await page.getByRole("combobox", { name: "Preview role" }).selectOption("super");
  await page.getByRole("button", { name: "Upload video", exact: true }).click();
  assert(await page.evaluate(() => document.activeElement?.getAttribute("name")) === "title", "Upload dialog did not focus title");
  await page.locator("input[type=file]").setInputFiles("/Users/jsonse/.codex/worktrees/org-guide-prototypes/race-pace/docs/previews/guide/index.html");
  await page.getByRole("alert").filter({ hasText: "Choose an MP4 or WebM video." }).waitFor();
  assert(await page.getByRole("button", { name: "Publish guide", exact: true }).isDisabled(), "Invalid file could publish");
  await page.locator("input[name=title]").fill("Uploaded preview check");
  await page.locator("textarea[name=description]").fill("Browser-only sample description.");
  await page.locator("input[type=file]").setInputFiles(sample);
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "Manage guides", exact: true }).click();
  await page.getByRole("heading", { name: "Uploaded preview check", exact: true }).waitFor();
  await page.getByRole("combobox", { name: "Preview role" }).selectOption("org");
  assert(await page.getByRole("heading", { name: "Uploaded preview check", exact: true }).count() === 0, "Org admin saw a draft");
  await page.getByRole("combobox", { name: "Preview role" }).selectOption("super");
  await page.getByRole("button", { name: "Manage guides", exact: true }).click();
  await page.locator(".gd-manage-row").first().getByRole("button", { name: "Edit guide" }).click();
  await page.getByRole("button", { name: "Publish changes", exact: true }).click();
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  await page.getByRole("combobox", { name: "Preview role" }).selectOption("org");
  await page.getByRole("heading", { name: "Uploaded preview check", exact: true }).waitFor();
  await page.locator(".gd-video-card").first().click();
  await page.locator("video").evaluate(async video => { await video.play(); });
  await page.waitForFunction(() => (document.querySelector("video")?.currentTime ?? 0) > 0);
  await page.keyboard.press("Escape");
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  await page.goto(`${base}?choice=3`);
  await page.getByRole("combobox", { name: "Preview role" }).selectOption("super");
  await page.getByRole("button", { name: "Manage guides", exact: true }).click();
  await page.locator(".gd-manage-row").filter({ hasText: "From new event to race ticket" }).getByRole("button", { name: "Edit guide" }).click();
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  await page.getByRole("combobox", { name: "Preview role" }).selectOption("org");
  assert(!(await page.locator("main").innerText()).includes("From new event to race ticket"), "Watch Desk exposed an existing guide converted to draft");
  await page.locator(".gd-choice-nav").getByRole("button", { name: /Video Library/ }).click();
  assert(await page.locator(".gd-feature").count() === 0, "Featured slot exposed a draft");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Open admin navigation" }).click();
  await page.getByRole("dialog", { name: "Admin navigation" }).waitFor();
  const bounds = await page.getByRole("dialog").boundingBox();
  assert(bounds?.x === 0 && bounds?.y === 0 && bounds?.width === 390 && bounds?.height === 844, "Mobile navigation does not fit viewport");
  for (let i = 0; i < 18; i++) await page.keyboard.press("Tab");
  assert(await page.evaluate(() => !!document.activeElement?.closest("[role=dialog]")), "Mobile navigation let keyboard focus escape");
  await page.keyboard.press("Escape");
  await page.getByRole("dialog").waitFor({ state: "hidden" });
  assert(await page.evaluate(() => document.activeElement?.getAttribute("aria-label")) === "Open admin navigation", "Mobile navigation did not restore focus");
  return { results, upload: "pass", draftIsolation: "pass", existingDraftIsolation: "pass", publish: "pass", playback: "pass", keyboard: "pass", mobileNavigation: "pass" };
}
